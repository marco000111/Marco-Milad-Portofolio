export function getPortfolio(language) {
  const copy = content[language] || content.en;
  const projects = [
    ...copy.concepts.map((item, index) => ({
      id: slugs[index],
      title: item[0],
      category: 'Website',
      type: ui[language].projectConcept,
      image: conceptImages[index],
      imageAlt: `${item[0]} website concept screenshot`,
      brief: item[2],
      description: item[3],
      stack: item[4].split(' · '),
      liveUrl: `/demos/${slugs[index]}/`,
      sourceUrl: `https://github.com/marco000111/Marco-Milad-Portofolio/tree/portfolio-v2/demos/${slugs[index]}`,
      language,
    })),
    ...copy.apps.map((item, index) => ({
      id: `app-${index + 1}`,
      title: item[0],
      category: 'Web app',
      type: ui[language].webApplication,
      image: item[2].startsWith('/') ? item[2] : `/${item[2]}`,
      imageAlt: `${item[0]} application screenshot`,
      brief: item[1],
      description: item[1],
      stack: [],
      liveUrl: item[3],
      sourceUrl: '',
      language,
    })),
    {
      id: 'omar-editezzz',
      title: 'Omar Editezzz',
      category: 'Website',
      type: ui[language].videoEditorPortfolio,
      image: '/assets/images/omar-editezzz.png',
      imageAlt: 'Omar Editezzz video editor portfolio homepage',
      brief: language === 'ar'
        ? 'موقع سينمائي حديث يقدّم أعمال عمر في المونتاج وسرد القصص البصري والحركة السلسة.'
        : 'A modern cinematic portfolio shaped by video editing, visual storytelling, and smooth motion.',
      description: language === 'ar'
        ? 'موقع إبداعي حديث لعمر إديتز، صُمم حول مونتاج الفيديو وسرد القصص البصري والحركة السلسة والتجارب التفاعلية المميزة.'
        : 'A modern cinematic portfolio website for Omar Editezzz, designed around video editing, visual storytelling, smooth motion, and a premium interactive experience.',
      stack: [],
      liveUrl: 'https://omar-editezz.vercel.app/',
      sourceUrl: '',
      language,
    },
  ];

  return {
    content: copy,
    ui: ui[language] || ui.en,
    projects,
    skills: skillList,
    skillCategories: categoryMap[language] || categoryMap.en,
  };
}

